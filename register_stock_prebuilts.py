"""Declare stock recovery ELFs as checked Android prebuilt modules; run in build WSL."""
import hashlib
from pathlib import Path
import re
import subprocess
import sys

base = Path(__file__).resolve().parent
device = base / 'device/realme/RMX3125'
tree = Path('/opt/twrp')
system = tree / 'out/target/product/RMX3125/recovery/root/system/lib64'
core = {name: system / name for name in ('libc.so', 'libm.so', 'libdl.so')}
elfs = {}
for line in (device / 'stock-blob-sha256.txt').read_text().splitlines():
    digest, relative, _ = line.split('  ', 2)
    path = (device / relative).resolve(strict=True)
    assert path.is_relative_to(device) and relative.startswith('recovery/root/vendor/'), relative
    data = path.read_bytes()
    assert hashlib.sha256(data).hexdigest() == digest, relative
    assert data[:5] == b'\x7fELF\x02' and data[18:20] == b'\xb7\x00', relative
    dynamic = subprocess.check_output(['readelf', '-dW', str(path)], text=True)
    needed = re.findall(r'Shared library: \[([^\]]+)\]', dynamic)
    sonames = re.findall(r'Library soname: \[([^\]]+)\]', dynamic)
    assert all('/' not in name for name in needed + sonames), relative
    library = path.suffix == '.so'
    assert not library or len(sonames) == 1, f'Missing SONAME: {relative}'
    elfs[relative] = dict(path=path, needed=needed, soname=sonames[0] if sonames else None,
                          library=library, digest=digest)

# HAL loader aliases must be symlinks; renaming a shared object contradicts its SONAME.
aliases = {}
canonical = {}
for relative, info in elfs.items():
    if info['library'] and info['soname'] != info['path'].name:
        target = str(Path(relative).with_name(info['soname']))
        assert target in elfs and elfs[target]['digest'] == info['digest'], relative
        aliases.setdefault(target, []).append(info['path'].name)
    else:
        canonical[relative] = info

libraries = {info['soname']: relative for relative, info in canonical.items() if info['library']}
assert len(libraries) == sum(info['library'] for info in canonical.values()), 'Duplicate SONAME'
names = {relative: 'rmx3125_stock_' + re.sub(r'[^A-Za-z0-9_]', '_', info['path'].stem)
         for relative, info in canonical.items()}
assert len(set(names.values())) == len(names), 'Duplicate module name'
for path in core.values():
    assert path.is_file(), f'Compiled recovery Bionic library missing: {path}'

blocks = ['# Generated by register_stock_prebuilts.py; stock payloads stay byte-identical.',
          '# SPDX-License-Identifier: Apache-2.0', 'LOCAL_PATH := $(call my-dir)',
          'ifeq ($(TARGET_DEVICE),RMX3125)', '']
for relative, info in sorted(canonical.items()):
    dependencies = []
    shared_files = []
    for needed in info['needed']:
        if needed in core:
            dependencies.append(needed[:-3] + '.recovery')
            shared_files.append(core[needed])
        else:
            assert needed in libraries, f'{relative}: missing dependency {needed}'
            dependency = libraries[needed]
            dependencies.append(names[dependency])
            shared_files.append(elfs[dependency]['path'])
    command = [sys.executable, str(tree / 'build/make/tools/check_elf_file.py'),
               '--llvm-readobj', str(tree / 'prebuilts/clang/host/linux-x86/clang-r547379/bin/llvm-readobj')]
    if info['library']:
        command += ['--soname', info['path'].name]
    for path in shared_files:
        command += ['--shared-lib', str(path)]
    command.append(str(info['path']))
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode:
        print(result.stdout, end='')
        print(result.stderr, end='', file=sys.stderr)
        raise SystemExit(result.returncode)
    filename = info['path'].name
    destination = Path(relative).parent.relative_to('recovery/root').as_posix()
    block = ['include $(CLEAR_VARS)', f'LOCAL_MODULE := {names[relative]}',
             f'LOCAL_SRC_FILES := {relative}',
             'LOCAL_MODULE_CLASS := ' + ('SHARED_LIBRARIES' if info['library'] else 'EXECUTABLES'),
             f'LOCAL_MODULE_STEM := {filename[:-3] if info["library"] else filename}',
             f'LOCAL_MODULE_PATH := $(TARGET_RECOVERY_ROOT_OUT)/{destination}',
             'LOCAL_MULTILIB := 64', 'LOCAL_SYSTEM_SHARED_LIBRARIES :=',
             'LOCAL_SHARED_LIBRARIES := ' + ' '.join(dependencies),
             'LOCAL_CXX_STL := none', 'LOCAL_STRIP_MODULE := false', 'LOCAL_CHECK_ELF_FILES := true']
    if info['library']:
        block.append('LOCAL_MODULE_SUFFIX := .so')
    if relative in aliases:
        block.append('LOCAL_MODULE_SYMLINKS := ' + ' '.join(sorted(aliases[relative])))
    blocks.extend(block + ['include $(BUILD_PREBUILT)', ''])
blocks += ['endif', '']
packages = ['# Generated by register_stock_prebuilts.py.', 'PRODUCT_PACKAGES += \\']
packages += ['    ' + name + (' \\' if index < len(names) - 1 else '')
             for index, name in enumerate(sorted(names.values()))]
(device / 'Android.mk').write_text('\n'.join(blocks))
(device / 'stock-prebuilts.mk').write_text('\n'.join(packages) + '\n')
print(f'PASS: {len(canonical)} stock prebuilt modules pass SONAME, DT_NEEDED and undefined-symbol checks.')
print(f'PASS: {sum(map(len, aliases.values()))} HAL aliases map to byte-identical canonical libraries.')
